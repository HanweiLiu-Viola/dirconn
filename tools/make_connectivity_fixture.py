"""Write the NetCDF results file used to prove that files from before the restructure still load.

The file is generated by the code at commit 0e2b04e and committed as
``tests/data/connectivity_main_0e2b04e.nc``. Run it again only to deliberately replace the fixture.
"""

from pathlib import Path

import dirconn
from dirconn import Edge, Network, dk_node
from dirconn.simulation import NodeDynamics, simulate

OUT = Path(__file__).resolve().parent.parent / "tests" / "data" / "connectivity_main_0e2b04e.nc"


def main() -> None:
    """Simulate the three-node chain, estimate conditional GC and write it to NetCDF."""
    a, b, c = "cuneus-rh", "precuneus-rh", "insula-rh"
    network = Network(
        nodes=[dk_node(a), dk_node(b), dk_node(c)],
        edges=[Edge(a, b, strength=0.4, delay_ms=10.0), Edge(b, c, strength=0.4, delay_ms=10.0)],
        name="chain",
    )
    dynamics = {
        a: NodeDynamics(kind="oscillator", freq_hz=10.0),
        b: NodeDynamics(kind="oscillator", freq_hz=20.0),
        c: NodeDynamics(kind="oscillator", freq_hz=15.0),
    }
    sim = simulate(
        network,
        sfreq=100.0,
        n_times=2000,
        seed=0,
        dynamics=dynamics,
        snr_db=10.0,
        n_background=0,
        node_scale="unit",
    )
    data = sim.roi_observations(snr_db=10.0, seed=1)
    result = dirconn.gc(data, order=3)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    result.to_netcdf(OUT)
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
